#!/usr/bin/env python3
"""Generate SPACEV-style ACL groundtruths for BigANN/SIFT1B.

Unfiltered groundtruth is copied from the official BigANN gnd archive when
available (idx_1000M.ivecs / dis_1000M.fvecs). Filtered ACL groundtruths are
computed exactly with FAISS L2 over the synthetic SPACEV-style tags generated by
gen_sift1b_attrs.py.
"""
import argparse
import json
import struct
import time
from datetime import datetime, timezone
from pathlib import Path

import faiss
import numpy as np

LEVEL_NAMES = ("org", "dept", "team", "project")
DEFAULT_SCENARIO = "/mnt/nvme/baotonglu/mocheng/datasets/sift1b/multitenant/tenant_tag_scenario.json"


def utc_timestamp() -> str:
    return datetime.now(timezone.utc).strftime("%Y-%m-%dT%H:%M:%SZ")


def read_ivecs(path: Path) -> np.ndarray:
    raw = np.fromfile(path, dtype=np.int32)
    if raw.size == 0:
        raise RuntimeError(f"empty vecs file: {path}")
    dim = int(raw[0])
    rec = dim + 1
    if raw.size % rec != 0:
        raise RuntimeError(f"{path} size {raw.size} not divisible by record {rec}")
    return np.ascontiguousarray(raw.reshape(raw.size // rec, rec)[:, 1:])


def read_fvecs(path: Path) -> np.ndarray:
    with open(path, "rb") as f:
        first = f.read(4)
        if len(first) != 4:
            raise RuntimeError(f"empty vecs file: {path}")
        dim = struct.unpack("<i", first)[0]
    rec_bytes = 4 + 4 * dim
    size = path.stat().st_size
    if size % rec_bytes != 0:
        raise RuntimeError(f"{path} size {size} not divisible by record bytes {rec_bytes}")
    out = np.empty((size // rec_bytes, dim), dtype=np.float32)
    with open(path, "rb") as f:
        for i in range(out.shape[0]):
            d = struct.unpack("<i", f.read(4))[0]
            if d != dim:
                raise RuntimeError(f"dimension mismatch in {path} row {i}: {d} != {dim}")
            out[i] = np.frombuffer(f.read(4 * dim), dtype=np.float32)
    return out


def find_official_gnd(raw_dir: Path) -> tuple[Path | None, Path | None]:
    candidates = [
        raw_dir / "gnd" / "idx_1000M.ivecs",
        raw_dir / "idx_1000M.ivecs",
        raw_dir / "bigann_gnd" / "idx_1000M.ivecs",
    ]
    idx = next((p for p in candidates if p.exists()), None)
    dist_candidates = [
        raw_dir / "gnd" / "dis_1000M.fvecs",
        raw_dir / "dis_1000M.fvecs",
        raw_dir / "bigann_gnd" / "dis_1000M.fvecs",
    ]
    dist = next((p for p in dist_candidates if p.exists()), None)
    return idx, dist


def load_base_u8(path: str, n: int, dim: int, chunk: int = 20_000_000) -> np.ndarray:
    raw = np.memmap(path, dtype=np.uint8, mode="r", offset=8, shape=(n, dim))
    out = np.empty((n, dim), dtype=np.float32)
    t0 = time.time()
    for s in range(0, n, chunk):
        e = min(s + chunk, n)
        out[s:e] = np.asarray(raw[s:e], dtype=np.float32)
        print(f"  base widen {e:,}/{n:,} ({time.time() - t0:.0f}s)", flush=True)
    del raw
    return out


def knn_l2(xq: np.ndarray, xb: np.ndarray, topk: int) -> tuple[np.ndarray, np.ndarray]:
    nq = xq.shape[0]
    out_pos = np.full((nq, topk), -1, dtype=np.int64)
    out_dist = np.full((nq, topk), np.inf, dtype=np.float32)
    if xb.shape[0] == 0:
        return out_pos, out_dist
    k = min(topk, xb.shape[0])
    d, i = faiss.knn(np.ascontiguousarray(xq, dtype=np.float32),
                     np.ascontiguousarray(xb, dtype=np.float32),
                     k, metric=faiss.METRIC_L2)
    out_pos[:, :k] = i
    out_dist[:, :k] = d
    return out_pos, out_dist


def parse_args() -> argparse.Namespace:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("--scenario-file", default=DEFAULT_SCENARIO)
    p.add_argument("--output-dir", default=None, help="Default: <scenario dir>/query")
    p.add_argument("--raw-dir", default=None, help="Default: <dataset root>/raw")
    p.add_argument("--topk", type=int, default=100)
    p.add_argument("--threads", type=int, default=64)
    p.add_argument("--query-batch", type=int, default=4096)
    p.add_argument("--num-queries", type=int, default=0, help="0 = all")
    p.add_argument("--levels", default="unfilter,org,dept,team,project")
    return p.parse_args()


def main() -> None:
    args = parse_args()
    faiss.omp_set_num_threads(args.threads)
    scenario_path = Path(args.scenario_file)
    scenario = json.loads(scenario_path.read_text(encoding="utf-8"))
    sdir = scenario_path.parent
    root = sdir.parent
    raw_dir = Path(args.raw_dir) if args.raw_dir else root / "raw"
    output_dir = Path(args.output_dir) if args.output_dir else sdir / "query"
    output_dir.mkdir(parents=True, exist_ok=True)
    want = set(s.strip() for s in args.levels.split(",") if s.strip())

    n = int(scenario["vector_count"])
    dim = int(scenario["dimension"])
    data_file = scenario["data_file"]
    tag_file = scenario["attributes"]["acl"]["file"]
    topk = args.topk

    qv_all = np.ascontiguousarray(np.load(output_dir / "query_vectors.npy"), dtype=np.float32)
    qtags_all = np.ascontiguousarray(np.load(output_dir / "query_tags.npy"), dtype=np.uint32)
    nq = qv_all.shape[0] if args.num_queries <= 0 else min(args.num_queries, qv_all.shape[0])
    qv = qv_all[:nq]
    qtags = qtags_all[:nq]
    print(f"queries: {nq} x {dim} topk={topk} threads={args.threads}", flush=True)

    def save(name: str, ids: np.ndarray, dists: np.ndarray) -> None:
        np.save(output_dir / f"groundtruth_{name}_local_ids.npy", ids.astype(np.int64, copy=False))
        np.save(output_dir / f"groundtruth_{name}_dists.npy", dists.astype(np.float32, copy=False))
        print(f"  saved groundtruth_{name}_local_ids.npy", flush=True)

    if "unfilter" in want:
        idx_path, dist_path = find_official_gnd(raw_dir)
        if idx_path is None:
            raise FileNotFoundError(f"official idx_1000M.ivecs not found under {raw_dir}")
        ids = read_ivecs(idx_path)[:nq, :topk].astype(np.int64)
        if dist_path is not None:
            dists = read_fvecs(dist_path)[:nq, :topk]
        else:
            dists = np.full(ids.shape, np.nan, dtype=np.float32)
        save("unfilter", ids, dists)

    filtered = [name for name in LEVEL_NAMES if name in want]
    if filtered:
        print("loading + widening base ...", flush=True)
        base = load_base_u8(data_file, n, dim)
        tags = np.load(tag_file, mmap_mode="r")
        for level, name in enumerate(LEVEL_NAMES):
            if name not in want:
                continue
            t0 = time.time()
            pos = np.full((nq, topk), -1, dtype=np.int64)
            dist = np.full((nq, topk), np.inf, dtype=np.float32)
            col = np.ascontiguousarray(tags[:, level], dtype=np.uint32)
            qval = qtags[:, level].astype(np.uint32)
            for tag_value in np.unique(qval).tolist():
                group = np.flatnonzero(qval == tag_value)
                cand_ids = np.flatnonzero(col == np.uint32(tag_value)).astype(np.int64)
                sub = np.ascontiguousarray(base[cand_ids])
                for s in range(0, group.size, args.query_batch):
                    rows = group[s:s + args.query_batch]
                    sp, sd = knn_l2(qv[rows], sub, topk)
                    valid = sp >= 0
                    mapped = np.where(valid, cand_ids[np.where(valid, sp, 0)], -1)
                    pos[rows] = mapped
                    dist[rows] = sd
                del sub
                print(f"  {name} tag={tag_value} cand={cand_ids.size:,} grp={group.size} ({time.time() - t0:.0f}s)", flush=True)
            del col
            save(name, pos, dist)

    meta = {
        "created_at_utc": utc_timestamp(),
        "scenario_file": str(scenario_path.resolve()),
        "dataset": "sift1b",
        "tenant": 0,
        "num_queries": int(nq),
        "topk": topk,
        "metric": "l2",
        "id_space": "tenant_local(==global, single tenant)",
        "query_types": [x for x in ("unfilter",) + LEVEL_NAMES if x in want],
        "vector_count": n,
        "groundtruth_files": {
            nm: f"groundtruth_{nm}_local_ids.npy"
            for nm in (("unfilter",) + LEVEL_NAMES)
            if nm in want
        },
    }
    (output_dir / "query_meta.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
    print(f"done. output_dir = {output_dir}", flush=True)


if __name__ == "__main__":
    main()
